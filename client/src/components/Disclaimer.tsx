function Disclaimer({ language = 'en' }: Props) {
  return (
    <div
      role="note"
      className="border border-charcoal-700 p-4 text-sm text-muted print:border-slate-400 print:text-black"
    >
      <p>
        <strong className="text-paper print:text-black">
          This tool does not provide legal advice.
        </strong>{' '}
        The analysis is generated by AI and may contain mistakes. Consult a
        qualified lawyer before signing or relying on any contract.
      </p>
      {language === 'my' && (
        <p lang="my" className="mt-3 border-t border-charcoal-700 pt-3">
          {DISCLAIMER_MY}
        </p>
      )}
    </div>
  )
}

export default Disclaimer
